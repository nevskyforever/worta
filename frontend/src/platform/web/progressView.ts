import type { BrowserProjectProgress } from './progressApply'
import { progressMicros, type ProgressFact } from '@/cloud/progressCodec'
import { progressDisplay } from '@/cloud/progressTransition'
import { calculatePureStatistics } from '@/core/statistics/calculations'
import { progressPercentage, remainingToGoal } from '@/core/projects/calculations'

export interface ProgressSettings { unit: ProgressFact['unit']; goal: number | null; infinite: boolean; created_at: string | null }
/** Same fixed-symbol facts and pure statistics used by Desktop. No game reward,
 * mutation, local planning state or inferred streak is generated by reading. */
export function presentProgress(chain: BrowserProjectProgress, settings: ProgressSettings, planningDate: string, aggregateTotal?: number) {
  const last = chain.entries.at(-1)
  const total = aggregateTotal ?? progressDisplay(progressMicros(last?.new_total ?? chain.base_total), settings.unit, last?.unit ?? settings.unit)
  const goal = { goal: settings.goal, infinite: settings.infinite, total }
  const entries = chain.entries.map(f => ({ ...f,
    total: progressDisplay(progressMicros(f.new_total), settings.unit, f.unit),
    added: progressDisplay(progressMicros(f.delta), settings.unit, f.unit),
    added_symbols: Number(progressMicros(f.delta)) / 1e6,
  }))
  return { ...chain, unit: settings.unit, goal: settings.infinite ? null : settings.goal, total,
    progress: progressPercentage(goal), remaining: remainingToGoal(goal), entries,
    statistics: calculatePureStatistics({ entityId: chain.stage_id ?? chain.project_id, unit: settings.unit, total,
      createdAt: settings.created_at, planningDate, progressEntries: entries.map(f => ({
        createdAt: f.occurred_at ?? f.writing_time!, writingDay: f.writing_day, addedSymbols: f.added_symbols,
      })) }),
  }
}
export type BrowserProgressView = ReturnType<typeof presentProgress>
